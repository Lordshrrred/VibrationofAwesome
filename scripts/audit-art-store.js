import fs from "node:fs";
import path from "node:path";
import vm from "node:vm";
import { fileURLToPath } from "node:url";
import sharp from "sharp";

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const storeFile = path.join(repoRoot, "static/art-store/index.html");
const catalogFile = path.join(repoRoot, "data/art-store/catalog-inventory.json");
const reportFile = path.join(repoRoot, "reports/art-store-inventory.md");

function extractStore(html) {
  const startMarker = "var STORE = ";
  const start = html.indexOf(startMarker);
  if (start === -1) throw new Error("Could not find the live Art Store product data.");
  const objectStart = start + startMarker.length;
  const end = html.indexOf("\n  };", objectStart);
  if (end === -1) throw new Error("Could not find the end of the live Art Store product data.");
  return vm.runInNewContext(`(${html.slice(objectStart, end + 4)})`, Object.create(null), { timeout: 1_000 });
}

function flattenProducts(store) {
  const rows = [];
  for (const [designId, design] of Object.entries(store)) {
    for (const [productType, value] of Object.entries(design)) {
      if (productType === "label") continue;
      const products = Array.isArray(value) ? value : [value];
      for (const product of products) {
        if (!product || typeof product !== "object") continue;
        rows.push({
          designId,
          designTitle: design.label,
          productType: productType === "shirts" ? "shirt" : productType,
          name: product.name,
          description: product.desc ?? null,
          springUrl: product.url ?? null,
          images: (product.images ?? []).map(([src, view]) => ({ src, view })),
        });
      }
    }
  }
  return rows;
}

async function inspectImage(image) {
  const relativePath = image.src.split("?")[0].replace(/^\//, "static/");
  const absolutePath = path.join(repoRoot, relativePath);
  if (!fs.existsSync(absolutePath)) return { ...image, relativePath, exists: false };
  const metadata = await sharp(absolutePath).metadata();
  return {
    ...image,
    relativePath,
    exists: true,
    width: metadata.width ?? null,
    height: metadata.height ?? null,
    format: metadata.format ?? null,
    hasAlpha: metadata.hasAlpha ?? false,
    role: "storefront-mockup",
    printMaster: false,
  };
}

function markdown(catalog) {
  const missingImages = catalog.products.flatMap((product) => product.images.filter((image) => !image.exists));
  const missingLinks = catalog.products.filter((product) => !product.springUrl);
  const lowResolution = catalog.products.flatMap((product) => product.images.filter((image) => image.exists && Math.max(image.width ?? 0, image.height ?? 0) < 1_000));
  const lines = [
    "# EarthStar Art Store Inventory",
    "",
    "> Generated by `npm run art-store:audit`. The live `/art-store/` page is not modified.",
    "",
    "## What is true",
    "",
    `- ${catalog.summary.designs} live design worlds are represented by ${catalog.summary.products} Spring product records.`,
    `- ${catalog.summary.images} storefront mockup references were found; ${missingImages.length} referenced files are missing.`,
    `- ${missingLinks.length} product records lack a Spring checkout URL.`,
    "- No transparent, high-resolution production masters for these designs were found in this repository.",
    `- ${lowResolution.length} mockups are below 1000 px on their longest side. These are storefront previews, not printable source art.`,
    "",
    "## Design queue",
    "",
    "| Design | Products | Mockups | Technical status | Human decision |",
    "| --- | ---: | ---: | --- | --- |",
  ];

  for (const design of catalog.designs) {
    lines.push(`| ${design.title} | ${design.productCount} | ${design.imageCount} | Production master missing | Keep / repair / remaster |`);
  }

  lines.push(
    "",
    "## Simple next step",
    "",
    "Choose one pilot design. Locate or recover its original transparent artwork file. If no usable master exists, remaster that one design before creating colorways or new Spring listings.",
    "",
    "## Rules already locked",
    "",
    "- The current `/art-store/` stays live and unchanged.",
    "- The replacement will be built separately at `/art-store-v2/`.",
    "- Mockup JPGs are previews only and must never be uploaded as print artwork.",
    "- Normal workflow stays one-choice-at-a-time; technical controls remain under Advanced.",
    "- Spring listings begin private or unlisted and become public only after visual verification.",
    "",
  );
  return lines.join("\n");
}

async function main() {
  const html = fs.readFileSync(storeFile, "utf8");
  const products = flattenProducts(extractStore(html));
  for (const product of products) product.images = await Promise.all(product.images.map(inspectImage));

  const designMap = new Map();
  for (const product of products) {
    const current = designMap.get(product.designId) ?? { id: product.designId, title: product.designTitle, productCount: 0, imageCount: 0 };
    current.productCount += 1;
    current.imageCount += product.images.length;
    designMap.set(product.designId, current);
  }

  const catalog = {
    generatedAt: new Date().toISOString(),
    source: "static/art-store/index.html",
    productionRouteProtected: true,
    replacementRoute: "/art-store-v2/",
    summary: {
      designs: designMap.size,
      products: products.length,
      images: products.reduce((sum, product) => sum + product.images.length, 0),
      productionMastersFound: 0,
    },
    designs: [...designMap.values()],
    products,
  };

  fs.mkdirSync(path.dirname(catalogFile), { recursive: true });
  fs.mkdirSync(path.dirname(reportFile), { recursive: true });
  fs.writeFileSync(catalogFile, `${JSON.stringify(catalog, null, 2)}\n`);
  fs.writeFileSync(reportFile, markdown(catalog));
  console.log(`Wrote ${path.relative(repoRoot, catalogFile)}`);
  console.log(`Wrote ${path.relative(repoRoot, reportFile)}`);
  console.log(JSON.stringify(catalog.summary));
}

main().catch((error) => {
  console.error(error.message);
  process.exitCode = 1;
});
