/**
 * build-boom-index.js
 *
 * Bakes the Boom Frequency post list into static/blog/boom/index.html as real
 * HTML links, so crawlers see every post without running JavaScript.
 *
 * Why: the index used to fetch /_data/boom-posts.json in the browser, and
 * robots.txt disallows /_data/. Search engines saw an empty "Tuning in to
 * signal..." shell, so no post was linked from the Boom index.
 *
 * Invocation: `npm run build:boom-index`
 * Also called by drip-publish.js after boom-posts.json is updated.
 * Idempotent: content between the BOOM_POSTS markers is replaced each run.
 */
import fs from "fs";
import path from "path";
import { fileURLToPath } from "url";
import { cleanPublicPath } from "./lib/clean-url.js";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, "..");

const START = "<!-- BOOM_POSTS_START (generated by scripts/build-boom-index.js; do not edit) -->";
const END = "<!-- BOOM_POSTS_END -->";
const SHELL = '<div class="post-list" id="post-list"><div class="empty-state">Tuning in to signal...</div></div>';

const MONTHS = ["January", "February", "March", "April", "May", "June",
  "July", "August", "September", "October", "November", "December"];

function escapeHtml(value) {
  // House style (npm run check:emdash): no em dashes in published copy; use ~.
  return String(value ?? "")
    .replace(/\s*\u2014\s*/g, " ~ ")
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;");
}

function fmtDate(value) {
  const d = new Date(value);
  if (Number.isNaN(d.getTime())) return "";
  return `${MONTHS[d.getUTCMonth()]} ${d.getUTCDate()}, ${d.getUTCFullYear()}`;
}

function postUrl(p) {
  return cleanPublicPath(p.url || `/blog/boom/posts/${p.slug}`);
}

export function renderBoomPosts(posts) {
  return [...posts]
    .sort((a, b) => new Date(b.date) - new Date(a.date))
    .map((p) => {
      const url = postUrl(p);
      const keyword = p.keyword ? `<span class="post-keyword">${escapeHtml(p.keyword)}</span>` : "";
      return `<div class="post-item"><div class="post-meta"><span class="post-date">${fmtDate(p.date)}</span>${keyword}</div><h2 class="post-title"><a href="${url}">${escapeHtml(p.title)}</a></h2><p class="post-excerpt">${escapeHtml(p.excerpt)}</p><a href="${url}" class="post-read-more">Read more &#8594;</a></div>`;
    })
    .join("\n");
}

export function bakeBoomIndex({ root = ROOT } = {}) {
  const postsPath = path.join(root, "static", "_data", "boom-posts.json");
  const indexPath = path.join(root, "static", "blog", "boom", "index.html");
  const posts = JSON.parse(fs.readFileSync(postsPath, "utf8"));
  if (!Array.isArray(posts) || posts.length === 0) {
    throw new Error("boom-posts.json is empty; refusing to bake an empty index");
  }
  let html = fs.readFileSync(indexPath, "utf8");
  const block = `<div class="post-list" id="post-list">\n${START}\n${renderBoomPosts(posts)}\n${END}\n</div>`;

  if (html.includes(START) && html.includes(END)) {
    const re = /<div class="post-list" id="post-list">\s*<!-- BOOM_POSTS_START[\s\S]*?<!-- BOOM_POSTS_END -->\s*<\/div>/;
    if (!re.test(html)) throw new Error("Boom markers found but wrapper div did not match");
    html = html.replace(re, () => block);
  } else if (html.includes(SHELL)) {
    html = html.replace(SHELL, () => block);
  } else {
    throw new Error("Could not find the Boom post-list shell or markers in index.html");
  }

  // Drop the old client-side loader that fetched the robots-blocked JSON.
  html = html.replace(/\n\s*function fmtDate\(d\)\{[\s\S]*?loadBoombotPosts\(\);/, "");

  fs.writeFileSync(indexPath, html, "utf8");
  return posts.length;
}

import { pathToFileURL as __voaPathToFileURL } from "node:url";
const __voaIsCli = process.argv[1] && import.meta.url === __voaPathToFileURL(process.argv[1]).href;
if (__voaIsCli) {
  try {
    console.log(`Baked ${bakeBoomIndex()} Boom posts into static/blog/boom/index.html`);
  } catch (err) {
    console.error(err.message);
    process.exit(1);
  }
}
